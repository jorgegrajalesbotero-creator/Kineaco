let currentLang = "es";

export function setLang(lang) {
  currentLang = lang === "en" ? "en" : "es";
}

export function getLang() {
  return currentLang;
}

export function appLocale() {
  return currentLang === "en" ? "en-US" : "es-CO";
}

// Idioma inicial: lo guardado en este dispositivo o, si no hay, el idioma del celular/computador.
export function detectLang() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "es" || saved === "en") return saved;
  } catch { }
  if (typeof navigator !== "undefined" && (navigator.language || "").toLowerCase().startsWith("en")) return "en";
  return "es";
}

export function rememberLang(lang) {
  try {
    localStorage.setItem("lang", lang);
  } catch { }
}

export function tr(text, params) {
  let out = currentLang === "en" ? EN[text] ?? text : text;
  if (params) out = out.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? "").toString());
  return out;
}

// Iniciales de los días (lunes a domingo)
export function dayLetters() {
  return currentLang === "en" ? ["M", "T", "W", "T", "F", "S", "S"] : ["L", "M", "M", "J", "V", "S", "D"];
}

